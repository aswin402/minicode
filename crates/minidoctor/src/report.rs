//! Multi-surface report generators:
//! - `.minicode/minidoctor/NEEDEDFIX.md` (dual Human + AI Agent prioritized checklist)
//! - `.minicode/minidoctor/latest.json` & `.minicode/minidoctor/history.jsonl`
//! - `flutter_doctor`-inspired ANSI terminal report with non-TTY graceful fallback
//! - Compact token-budgeted AI agent summary & SARIF 2.1.0 export

use crate::scorer::render_sparkline;
use crate::types::{Diagnostic, DiagnosticCategory, DoctorReport, HistoryEntry, Severity};
use anyhow::{Context, Result};
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};

/// Canonical project-level artifact directory: `.minicode/minidoctor/`.
#[must_use]
pub fn artifacts_dir(workspace: &Path) -> PathBuf {
    workspace.join(".minicode").join("minidoctor")
}

/// Writes `.minicode/minidoctor/NEEDEDFIX.md`, `latest.json`, and appends `history.jsonl`.
/// Returns the workspace-relative path `.minicode/minidoctor/NEEDEDFIX.md`.
pub fn persist_workspace_artifacts(
    workspace: &Path,
    report: &mut DoctorReport,
    extra_export_md: Option<&Path>,
) -> Result<PathBuf> {
    let dir = artifacts_dir(workspace);
    fs::create_dir_all(&dir).with_context(|| format!("Failed to create {}", dir.display()))?;

    let rel_md = ".minicode/minidoctor/NEEDEDFIX.md".to_string();
    report.neededfix_path = Some(rel_md.clone());

    let md = format_neededfix_markdown(report);
    let md_path = dir.join("NEEDEDFIX.md");
    fs::write(&md_path, &md).with_context(|| format!("Failed to write {}", md_path.display()))?;

    if let Some(custom_path) = extra_export_md {
        if let Some(parent) = custom_path.parent() {
            if !parent.as_os_str().is_empty() {
                let _ = fs::create_dir_all(parent);
            }
        }
        fs::write(custom_path, &md)
            .with_context(|| format!("Failed to write custom export {}", custom_path.display()))?;
    }

    let json_path = dir.join("latest.json");
    let json = serde_json::to_string_pretty(report)?;
    fs::write(&json_path, json)
        .with_context(|| format!("Failed to write {}", json_path.display()))?;

    let history_entry = HistoryEntry {
        timestamp: report.generated_at.clone(),
        git_head: report.git_head.clone(),
        scope: report.scope_label.clone(),
        score: report.score.overall,
        criticals: report.score.criticals,
        errors: report.score.errors,
        warnings: report.score.warnings,
        dead_code: report.score.dead_code,
        files_scanned: report.profile.file_count,
    };
    if let Ok(line) = serde_json::to_string(&history_entry) {
        let hist_path = dir.join("history.jsonl");
        if let Ok(mut f) = OpenOptions::new()
            .create(true)
            .append(true)
            .open(&hist_path)
        {
            let _ = writeln!(f, "{line}");
        }
    }

    Ok(md_path)
}

/// Loads the last persisted `.minicode/minidoctor/latest.json` report if present.
#[must_use]
pub fn load_latest_report(workspace: &Path) -> Option<DoctorReport> {
    let path = artifacts_dir(workspace).join("latest.json");
    let text = fs::read_to_string(path).ok()?;
    serde_json::from_str::<DoctorReport>(&text).ok()
}

/// Generates the dual Human + AI Agent `NEEDEDFIX.md` remediation document
/// (combining `flutter_doctor`'s structured tables + `py_doctor`'s AI priority checklist).
#[must_use]
pub fn format_neededfix_markdown(report: &DoctorReport) -> String {
    let mut out = String::with_capacity(4096);
    let s = &report.score;

    out.push_str("# MiniDoctor Health Report (`NEEDEDFIX.md`)\n\n");
    out.push_str(&format!(
        "> Generated by **minidoctor v{}** on `{}` · Scope: `{}` · Duration: `{}ms`\n\n",
        report.version, report.generated_at, report.scope_label, report.duration_ms
    ));

    let delta_str = match s.delta_from_previous {
        Some(d) if d > 0 => format!(" (`+{d}` vs previous)"),
        Some(d) if d < 0 => format!(" (`{d}` vs previous)"),
        Some(_) => " (`±0` vs previous)".to_string(),
        None => String::new(),
    };
    out.push_str(&format!(
        "## Health Score: {} / 100 ({}) — {}{}\n\n",
        s.overall, s.grade, s.label, delta_str
    ));

    out.push_str("| Metric | Value |\n| :--- | :--- |\n");
    out.push_str(&format!(
        "| Detected Stacks | {} |\n",
        report.profile.stack_summary()
    ));
    out.push_str(&format!(
        "| Files Scanned | {} ({} LOC) |\n",
        report.profile.file_count, report.profile.total_loc
    ));
    out.push_str(&format!("| Criticals | {} |\n", s.criticals));
    out.push_str(&format!("| Errors | {} |\n", s.errors));
    out.push_str(&format!("| Warnings | {} |\n", s.warnings));
    out.push_str(&format!("| Dead Code / Duplicates | {} |\n", s.dead_code));
    out.push_str(&format!(
        "| Dimension Scores | Correctness {} · Security {} · Performance {} · Architecture {} · Maintainability {} |\n",
        s.correctness, s.security, s.performance, s.architecture, s.maintainability
    ));
    if let Some(ref head) = report.git_head {
        out.push_str(&format!("| Git HEAD | `{head}` |\n"));
    }
    if s.trend_history.len() > 1 {
        out.push_str(&format!(
            "| Trend | `{}` |\n",
            render_sparkline(&s.trend_history)
        ));
    }
    out.push('\n');

    let criticals_and_errors: Vec<&Diagnostic> = report
        .diagnostics
        .iter()
        .filter(|d| matches!(d.severity, Severity::Critical | Severity::Error))
        .collect();
    let warnings: Vec<&Diagnostic> = report
        .diagnostics
        .iter()
        .filter(|d| d.severity == Severity::Warning && d.category != DiagnosticCategory::DeadCode)
        .collect();
    let dead_items: Vec<&Diagnostic> = report
        .diagnostics
        .iter()
        .filter(|d| d.category == DiagnosticCategory::DeadCode)
        .collect();

    if !criticals_and_errors.is_empty() {
        out.push_str("## Criticals & Errors (Must Fix)\n\n");
        out.push_str(
            "| Severity | Rule | Location | Description |\n| :--- | :--- | :--- | :--- |\n",
        );
        for d in &criticals_and_errors {
            out.push_str(&format!(
                "| **{}** | `{}` | `{}` | {} |\n",
                d.severity.badge(),
                d.rule,
                d.location(),
                escape_md_cell(&d.message)
            ));
        }
        out.push('\n');
    }

    if !warnings.is_empty() {
        out.push_str("## Warnings (Should Fix)\n\n");
        out.push_str("| Rule | Location | Description |\n| :--- | :--- | :--- |\n");
        for d in warnings.iter().take(60) {
            out.push_str(&format!(
                "| `{}` | `{}` | {} |\n",
                d.rule,
                d.location(),
                escape_md_cell(&d.message)
            ));
        }
        if warnings.len() > 60 {
            out.push_str(&format!(
                "\n*…and {} more warnings (see `.minicode/minidoctor/latest.json`).*\n",
                warnings.len() - 60
            ));
        }
        out.push('\n');
    }

    if !dead_items.is_empty() {
        out.push_str("## Dead Code & Duplicates (Clean Up)\n\n");
        out.push_str("| Type | Location | Details |\n| :--- | :--- | :--- |\n");
        for d in &dead_items {
            let sub = d.dead_code_kind.map(|k| k.label()).unwrap_or("DEAD CODE");
            out.push_str(&format!(
                "| `{}` | `{}` | {} |\n",
                sub,
                d.location(),
                escape_md_cell(&d.message)
            ));
        }
        out.push('\n');
    }

    // ── AI Agent Remediation Checklist ───────────────────────────────────────
    out.push_str("---\n\n## Priority Fixes for AI Agent\n\n");
    out.push_str("> Read this file and resolve issues in priority order (`CRIT` → `ERR` → `WARN` → `DEAD`).\n");
    out.push_str(
        "> Re-run `project_doctor` or `/doctor` after edits to verify score improvement.\n\n",
    );

    if report.diagnostics.is_empty() {
        out.push_str("✅ **No issues detected!** Codebase is healthy across all active checks.\n");
        return out;
    }

    if !criticals_and_errors.is_empty() {
        out.push_str("### ✗ CRITICAL & ERRORS — Fix First\n\n");
        for (i, d) in criticals_and_errors.iter().enumerate() {
            out.push_str(&format!(
                "- [ ] **{}. [{}] `{}` at `{}`**\n  - **Issue:** {}\n  - **Fix:** {}\n",
                i + 1,
                d.severity.badge(),
                d.rule,
                d.location(),
                d.message,
                d.suggestion
            ));
            if let Some(ref snip) = d.snippet {
                out.push_str(&format!("  - **Code:** `{}`\n", snip.replace('`', "'")));
            }
        }
        out.push('\n');
    }

    if !warnings.is_empty() {
        out.push_str("### ⚠ WARNINGS — Fix Next\n\n");
        for (i, d) in warnings.iter().take(25).enumerate() {
            out.push_str(&format!(
                "- [ ] **{}. `{}` at `{}`** — {} (*Fix: {}*)\n",
                i + 1,
                d.rule,
                d.location(),
                d.message,
                d.suggestion
            ));
        }
        out.push('\n');
    }

    if !dead_items.is_empty() {
        out.push_str("### 🧹 DEAD CODE & DUPLICATES — Cleanup\n\n");
        for (i, d) in dead_items.iter().take(20).enumerate() {
            let sub = d.dead_code_kind.map(|k| k.label()).unwrap_or("DEAD");
            out.push_str(&format!(
                "- [ ] **{}. [{}] `{}`** — {} (*Fix: {}*)\n",
                i + 1,
                sub,
                d.location(),
                d.message,
                d.suggestion
            ));
        }
    }

    out
}

/// Token-budgeted structured report tailored for LLM tool responses (`project_doctor`).
#[must_use]
pub fn format_agent_compact_summary(report: &DoctorReport, max_items: usize) -> String {
    let s = &report.score;
    let mut out = String::new();
    let delta = match s.delta_from_previous {
        Some(d) if d > 0 => format!(" (+{d})"),
        Some(d) if d < 0 => format!(" ({d})"),
        _ => String::new(),
    };
    out.push_str(&format!(
        "MiniDoctor Health Score: {}/100 ({}, {}){} · Scope: {} · Stacks: {} · Files: {} ({}ms)\n",
        s.overall,
        s.grade,
        s.label,
        delta,
        report.scope_label,
        report.profile.stack_summary(),
        report.profile.file_count,
        report.duration_ms
    ));
    out.push_str(&format!(
        "Counts: {} critical, {} errors, {} warnings, {} dead code | Sub-scores: Correctness {}, Security {}, Perf {}, Arch {}, Maint {}\n",
        s.criticals, s.errors, s.warnings, s.dead_code,
        s.correctness, s.security, s.performance, s.architecture, s.maintainability
    ));
    if let Some(ref path) = report.neededfix_path {
        out.push_str(&format!("Workspace Checklist: `{path}`\n"));
    }

    if report.diagnostics.is_empty() {
        out.push_str("✓ 0 issues found.\n");
        return out;
    }

    out.push_str("\nTop Prioritized Findings:\n");
    for d in report.diagnostics.iter().take(max_items) {
        let sub = d
            .dead_code_kind
            .map(|k| format!("[{}] ", k.label()))
            .unwrap_or_default();
        out.push_str(&format!(
            "- [{}] {}`{}` {} — {} | Fix: {}\n",
            d.severity.badge(),
            sub,
            d.rule,
            d.location(),
            d.message,
            d.suggestion
        ));
    }
    if report.diagnostics.len() > max_items {
        out.push_str(&format!(
            "... and {} more findings (full list in `.minicode/minidoctor/NEEDEDFIX.md`).\n",
            report.diagnostics.len() - max_items
        ));
    }
    out
}

/// Renders `flutter_doctor`-inspired ANSI terminal output with automatic non-TTY degradation.
#[must_use]
pub fn format_terminal_report(report: &DoctorReport, verbose: bool, use_color: bool) -> String {
    let c = |code: &str, txt: &str| -> String {
        if use_color {
            format!("{code}{txt}\x1b[0m")
        } else {
            txt.to_string()
        }
    };

    let mut out = String::new();
    let s = &report.score;

    out.push('\n');
    out.push_str(&format!(
        "  {} {}\n",
        c("\x1b[1;38;2;162;119;255m", "🩺 minidoctor"),
        c(
            "\x1b[90m",
            &format!("v{} · {}", report.version, report.scope_label)
        )
    ));
    out.push_str(&format!(
        "  {} {} · {} files ({} LOC) · {}ms\n\n",
        c("\x1b[32m", "✓"),
        c("\x1b[1m", &report.profile.stack_summary()),
        report.profile.file_count,
        report.profile.total_loc,
        report.duration_ms
    ));

    let rule_line = c(
        "\x1b[90m",
        "  ────────────────────────────────────────────────────────────────────────────",
    );

    // 1. Criticals & Errors
    let errs: Vec<&Diagnostic> = report
        .diagnostics
        .iter()
        .filter(|d| matches!(d.severity, Severity::Critical | Severity::Error))
        .collect();
    if !errs.is_empty() {
        out.push_str(&rule_line);
        out.push_str(&format!(
            "\n\n  {}\n\n",
            c(
                "\x1b[1;31m",
                &format!("ERRORS & CRITICALS ({})", errs.len())
            )
        ));
        for d in errs.iter().take(if verbose { 80 } else { 15 }) {
            let tag = if d.severity == Severity::Critical {
                c("\x1b[41;97;1m", " CRIT ")
            } else {
                c("\x1b[41;97m", " ERR  ")
            };
            out.push_str(&format!(
                "  {tag}  {:<34}  {}\n",
                c("\x1b[36m", &d.rule),
                c("\x1b[90m", &d.location())
            ));
            out.push_str(&format!("          {}\n", d.message));
            if verbose {
                out.push_str(&format!(
                    "          {} {}\n",
                    c("\x1b[32m", "Fix →"),
                    d.suggestion
                ));
            }
            out.push('\n');
        }
    }

    // 2. Warnings
    let warns: Vec<&Diagnostic> = report
        .diagnostics
        .iter()
        .filter(|d| d.severity == Severity::Warning && d.category != DiagnosticCategory::DeadCode)
        .collect();
    if !warns.is_empty() {
        out.push_str(&rule_line);
        out.push_str(&format!(
            "\n\n  {}\n\n",
            c("\x1b[1;33m", &format!("WARNINGS ({})", warns.len()))
        ));
        for d in warns.iter().take(if verbose { 60 } else { 10 }) {
            let tag = c("\x1b[43;30m", " WARN ");
            out.push_str(&format!(
                "  {tag}  {:<34}  {}\n",
                c("\x1b[36m", &d.rule),
                c("\x1b[90m", &d.location())
            ));
            out.push_str(&format!("          {}\n", d.message));
            if verbose {
                out.push_str(&format!(
                    "          {} {}\n",
                    c("\x1b[32m", "Fix →"),
                    d.suggestion
                ));
            }
            out.push('\n');
        }
    }

    // 3. Dead Code
    let deads: Vec<&Diagnostic> = report
        .diagnostics
        .iter()
        .filter(|d| d.category == DiagnosticCategory::DeadCode)
        .collect();
    if !deads.is_empty() {
        out.push_str(&rule_line);
        out.push_str(&format!(
            "\n\n  {}\n\n",
            c(
                "\x1b[1;90m",
                &format!("DEAD CODE & DUPLICATES ({})", deads.len())
            )
        ));
        for d in deads.iter().take(if verbose { 40 } else { 8 }) {
            let tag = c("\x1b[44;97m", " DEAD ");
            let sub = d.dead_code_kind.map(|k| k.label()).unwrap_or("DEAD");
            out.push_str(&format!(
                "  {tag}  {:<15}  {}\n",
                c("\x1b[90m", sub),
                c("\x1b[37m", &d.location())
            ));
            out.push_str(&format!("          {}\n\n", d.message));
        }
    }

    // 4. Hero Health Score Card (flutter_doctor signature box, exact 75-cell interior width)
    const BOX_INNER_W: usize = 75;
    let score_color = if s.overall >= 75 {
        "\x1b[32m"
    } else if s.overall >= 50 {
        "\x1b[33m"
    } else {
        "\x1b[31m"
    };
    let bar_w = 52usize;
    let filled = ((s.overall as usize) * bar_w) / 100;
    let empty = bar_w.saturating_sub(filled);
    let bar = format!(
        "{}{}",
        c(score_color, &"━".repeat(filled)),
        c("\x1b[90m", &"─".repeat(empty))
    );

    let score_cell = format!("{:<10}", format!("{} ({})", s.overall, s.grade));
    let title_plain = "HEALTH SCORE";
    let spark_plain = if s.trend_history.len() > 1 {
        format!("Trend {}", render_sparkline(&s.trend_history))
    } else {
        String::new()
    };
    let l1_used = 2 + 10 + 2 + title_plain.len() + spark_plain.chars().count() + 2;
    let l1_gap = BOX_INNER_W.saturating_sub(l1_used);

    let label_cell = format!("{:<10}", s.label);
    let stats_raw = format!(
        "{} crit · {} err · {} warn · {} dead · {} files",
        s.criticals, s.errors, s.warnings, s.dead_code, report.profile.file_count
    );
    let l3_used = 2 + 10 + 2 + stats_raw.chars().count() + 2;
    let l3_gap = BOX_INNER_W.saturating_sub(l3_used);
    let bar_pad_right = BOX_INNER_W.saturating_sub(14 + bar_w);

    out.push_str(&format!(
        "  {}\n",
        c("\x1b[90m", &format!("╭{}╮", "─".repeat(BOX_INNER_W)))
    ));
    out.push_str(&format!(
        "  {}  {}  {}{}{}  {}\n",
        c("\x1b[90m", "│"),
        c(score_color, &score_cell),
        c("\x1b[90m", title_plain),
        " ".repeat(l1_gap),
        c("\x1b[36m", &spark_plain),
        c("\x1b[90m", "│"),
    ));
    out.push_str(&format!(
        "  {}              {}{}{}\n",
        c("\x1b[90m", "│"),
        bar,
        " ".repeat(bar_pad_right),
        c("\x1b[90m", "│")
    ));
    out.push_str(&format!(
        "  {}  {}  {}{}  {}\n",
        c("\x1b[90m", "│"),
        c(score_color, &label_cell),
        stats_raw,
        " ".repeat(l3_gap),
        c("\x1b[90m", "│")
    ));
    out.push_str(&format!(
        "  {}\n\n",
        c("\x1b[90m", &format!("╰{}╯", "─".repeat(BOX_INNER_W)))
    ));

    // 5. Top Priority Fixes
    let top = report.top_priority_diagnostics(3);
    if !top.is_empty() {
        out.push_str("  Top priority fixes:\n");
        for d in top {
            out.push_str(&format!(
                "  {} Fix {} ({}) — {}\n",
                c("\x1b[31m", "→"),
                c("\x1b[36m", &d.rule),
                c("\x1b[90m", &d.location()),
                d.message
            ));
        }
        out.push('\n');
    }

    if let Some(ref md_path) = report.neededfix_path {
        out.push_str(&format!(
            "  {} Saved AI + human remediation checklist to {}\n",
            c("\x1b[32m", "✓"),
            c("\x1b[36m", md_path)
        ));
    }
    out.push_str(&format!(
        "  Tip: Run {} inside minicode to auto-fix, or {} for PR mode.\n",
        c("\x1b[36m", "/doctor fix"),
        c("\x1b[36m", "minidoctor . --diff main")
    ));

    out
}

/// Emits SARIF 2.1.0 JSON compatible with GitHub Code Scanning.
#[must_use]
pub fn format_sarif_json(report: &DoctorReport) -> String {
    let results: Vec<serde_json::Value> = report
        .diagnostics
        .iter()
        .map(|d| {
            let level = match d.severity {
                Severity::Critical | Severity::Error => "error",
                Severity::Warning => "warning",
                Severity::Info => "note",
            };
            serde_json::json!({
                "ruleId": d.rule,
                "level": level,
                "message": { "text": format!("{} — Fix: {}", d.message, d.suggestion) },
                "locations": [{
                    "physicalLocation": {
                        "artifactLocation": { "uri": d.file },
                        "region": { "startLine": d.line.max(1), "startColumn": d.column.max(1) }
                    }
                }]
            })
        })
        .collect();

    let sarif = serde_json::json!({
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {
                "driver": {
                    "name": "minidoctor",
                    "version": report.version,
                    "informationUri": "https://github.com/aswin402/minicode"
                }
            },
            "results": results
        }]
    });

    serde_json::to_string_pretty(&sarif).unwrap_or_else(|_| "{}".to_string())
}

fn escape_md_cell(raw: &str) -> String {
    raw.replace('|', "\\|").replace('\n', " ")
}
