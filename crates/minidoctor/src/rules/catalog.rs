/// Returns all built-in `minidoctor` rule metadata entries.
#[must_use]
pub const fn list_rules() -> &'static [RuleMeta] {
    RULE_CATALOG
}

/// Looks up a rule's full documentation by exact ID or suffix.
#[must_use]
pub fn explain_rule(rule_id: &str) -> Option<&'static RuleMeta> {
    let needle = rule_id.trim().to_ascii_lowercase();
    RULE_CATALOG
        .iter()
        .find(|r| r.id.eq_ignore_ascii_case(&needle))
        .or_else(|| {
            RULE_CATALOG
                .iter()
                .find(|r| r.id.to_ascii_lowercase().ends_with(&needle))
        })
}
